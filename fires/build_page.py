CROP_FLOOR = 50

# Cropland enrichment. Fire's thresholds, read from the payload's own
# `reading` field rather than recomputed, so the renderer never decides
# what counts.
def _land_use(e):
    """Where this week's detections fell, and what that cannot tell us.

    WHY THIS EXISTS. Cuba was the loudest claim on the site, selected by z
    from the corroborated set. Fire's cropland check found its detections
    fall 2.64 times more often on farmland than Cuban land does, stable
    across two independent weeks. Product ruled the headline came off.

    IT IS RENDERED RATHER THAN REMOVED, which was fire's call and the
    better one. Cuba really did record 1,176 detections against a mean of
    106. The finding does not make the number false; it changes what the
    number is EVIDENCE OF, and that is a fact to show rather than a reason
    to hide the biggest thing on the page.

    THE LIMIT IS THE LOAD-BEARING PART. VIIRS returns a thermal anomaly, a
    time and a radiative power. It does not see what is alight, so
    "agricultural burning" is an inference from where the heat sits against
    a land-cover mask, not a measurement of substrate. Fire got this exact
    distinction wrong on Serbia in the other direction this week, which is
    why the page carries the limit rather than only the conclusion.

    WITHHELD IS NOT ZERO, AND THERE ARE TWO OF THEM. The crop mask lives in
    the crops channel's gitignored cache, so CI cannot see it and the field
    reads mask_unavailable on every scheduled build: that means WE could
    not look. Papua New Guinea reads no_mask_coverage, which means the mask
    has no data there at all. Different facts, not merged into one grey.
    """
    lu = e.get("land_use") or {}
    reading = lu.get("reading") or lu.get("withheld")
    if not reading:
        return ""
    if reading in ("mask_unavailable", "no_mask_coverage", "withheld"):
        # ONE SENTENCE FOR BOTH WITHHOLDINGS, on fire's request and their
        # reasoning: mask_unavailable means our crop mask was missing from
        # the machine that built the payload; no_mask_coverage means the
        # mask holds no data for that country at all. The distinction
        # matters to us and not to a reader, who needs only "we cannot
        # say". I had rendered two different sentences, which put our CI
        # plumbing on a public page.
        return ('<p class="lu lu-na"><b>Where the detections fell: not '
                'assessed.</b> The cropland comparison could not be made '
                'for this country, so nothing here says whether these fires '
                'sit on farmland.</p>')

    ratio, on, land = (lu.get("cropland_ratio"),
                       lu.get("detections_on_crop_pct"),
                       lu.get("country_land_crop_pct"))
    if ratio is None or on is None or land is None:
        return ""

    # THE RATIO IS ONLY AS GOOD AS THE DETECTIONS ACTUALLY ON FARMLAND,
    # which is count times the share, not the count. Fire's own finding
    # after I sent them Peru, and it is a defect in a field already live on
    # these pages.
    #
    # Peru read 5.04x, the highest enrichment in Latin America, on about
    # TWENTY detections actually on cropland. Ecuador read 7.64x on about
    # seven. Cuba's 2.64x rests on 359. Same statistic, entirely different
    # weight. Fire's 50-detection floor did not catch it because it counts
    # every detection rather than the ones the ratio is computed from.
    #
    # They checked the obvious explanation first and it was wrong: the
    # correlation between cropland share and ratio is only -0.196, with
    # Georgia at 16.68 on a 5% share contradicting it. So this is not small
    # denominators inflating a ratio, it is a small numerator carrying one.
    # READ, NEVER RECONSTRUCTED, and this paragraph is why the rule exists
    # rather than an illustration of it. It used to compute the numerator
    # as n * pct / 100, taking n from `n_detections_sampled` with a
    # fallback to e["count"]. The block emitted neither and events.json has
    # no `count` key, so n was 0, on_crop was 0, and the floor fired on the
    # lead country: "About 0 of this week's detections fell on cropland,
    # which is too small a number to compare against chance", above the
    # fold, four lines above Cuba's row reading "on farmland 2.42x more
    # often than chance" off 208 detections actually on cropland.
    #
    # ONE PAYLOAD, TWO CONSUMERS, OPPOSITE STATEMENTS FOUR LINES APART, and
    # the difference between them was that _lu_row read the field while
    # this derived it. Both now read the same one. Fire's sign-off could
    # not have caught it: every threshold, value, row and string was
    # correct, and the defect lived in arithmetic a reviewer of the payload
    # never sees.
    #
    # Absent is a refusal rather than a zero. A missing numerator silently
    # became "too few to say", which is a confident claim about the data
    # built out of not having any.
    on_crop = lu.get("detections_on_crop")
    if on_crop is None:
        raise SystemExit(
            "%s: land_use has no detections_on_crop, so the cropland floor "
            "has no numerator. Fires emits this field; deriving it here is "
            "what published 'about 0 detections' beside a 2.42x row. The "
            "page will not be built without it." % e.get("country", "?"))
    if on_crop < CROP_FLOOR:
        return ('<p class="lu lu-na"><b>Where the detections fell: too few '
                'to say.</b> About %d of this week&rsquo;s detections fell on '
                'cropland, which is too small a number to compare against '
                'chance.</p>' % round(on_crop))
    if reading == "enriched":
        lede = ("%.1f%% of this week&rsquo;s detections fell on cropland, "
                "against the %.1f%% of this country that IS cropland. That "
                "is %.2f times more often than chance." % (on, land, ratio))
        rest = ("Fires this concentrated on farmland are usually deliberate "
                "and seasonal rather than wildfire.")
    elif reading == "depleted":
        lede = ("%.1f%% of this week&rsquo;s detections fell on cropland "
                "against the %.1f%% of this country that IS cropland, so "
                "they sit on farmland LESS often than chance."
                % (on, land))
        rest = "Whatever is burning here, it is mostly not farmland."
    else:
        lede = ("%.1f%% of this week&rsquo;s detections fell on cropland, "
                "against the %.1f%% of this country that IS cropland: about "
                "what chance would give." % (on, land))
        rest = "Nothing here points at farmland either way."
    return ('<p class="lu"><b>Where the detections fell.</b> %s %s '
            '<span class="lu-lim">The instrument sees a thermal anomaly, a '
            'time and a radiative power. It does not see what is alight, so '
            'this is an inference from where the heat sits against a '
            'land-cover map, not a measurement of what burned.</span></p>'
            % (lede, rest))


def _lu_row(e):
    """This country's cropland reading, on its own row.

    IT MUST APPEAR ON EVERY ROW OR IT IS A SELECTION EFFECT. Fire's catch
    and they are right: rendered only under the headline, the qualification
    showed up exactly when a country looked agricultural. Cuba read
    enriched at 2.64 and got a paragraph; Indonesia at 0.56 and Uganda at
    0.31 are just as informative and argue the OTHER way, that those fires
    sit on LESS farmland than chance, and both were invisible. A row that
    appears only when the number is awkward is the selection effect we keep
    catching in other people's work.

    Compact, because the explanation belongs once and the reading belongs
    everywhere. The paragraph under the headline carries the method and the
    limit; these carry each country's own number.
    """
    lu = e.get("land_use") or {}
    # THE WITHHELD KEY IS NOT `reading`. Fire emits {"withheld": "..."} with
    # no reading at all, so an earlier `if not reading: return ""` made
    # Papua New Guinea render NOTHING: the one country the mask genuinely
    # cannot see was the one country that said nothing, which is
    # absence-as-zero on the exact field built to prevent it.
    reading = lu.get("reading") or lu.get("withheld")
    if not reading:
        return ""
    if reading in ("mask_unavailable", "no_mask_coverage", "withheld"):
        return '<span class="rowlu rowlu-na">cropland: not assessed</span>'
    # TOO FEW TO COMPARE IS A READING, NOT A BLANK. Fire floored the
    # enriched claim on detections actually ON cropland, which is the count
    # the claim is made of, and withheld six readings. With no case here
    # they fell through `ratio is None` and rendered NOTHING, so Tunisia's
    # cropland line went absent from the live index rather than qualified.
    #
    # That is the selection effect this row exists to prevent, failing in
    # the quiet direction: the line disappeared on the one country where
    # the number was awkward. Fire took the gap deliberately over a
    # reversed line, which was right, and the numerator rides in the
    # payload so the row can say how few.
    if reading == "insufficient_sample":
        n = lu.get("detections_on_crop")
        if n is None:
            return ('<span class="rowlu rowlu-na">too few detections on '
                    'farmland to compare</span>')
        k = round(n)
        return ('<span class="rowlu rowlu-na">only %d detection%s on '
                'farmland, too few to compare against chance</span>'
                % (k, "" if k == 1 else "s"))
    ratio = lu.get("cropland_ratio")
    if ratio is None:
        return ""
    if reading == "neutral":
        return ('<span class="rowlu">on farmland about as often as '
                'chance</span>')
    word = "more" if reading == "enriched" else "less"
    return ('<span class="rowlu">on farmland %.2f&times; %s often than '
            'chance</span>' % (ratio, word))


def _persist_row(e):
    """Whether this week's heat behaves like fire or like a fixed source.

    THE SECOND OF THE TWO WAYS A BIG NUMBER CAN BE FALSE, and until now the
    page rendered only the first. Cuba carried its cropland reading and
    nothing saying it was not a flare artifact, while Saudi Arabia and
    Libya had been removed from the qualifying set on exactly this test
    without the page ever saying so.

    Rendered on EVERY row for the same reason the cropland line is: a check
    that appears only when it fails is a selection effect. 20 of 21 read
    fire_like, which is what makes the one that does not mean something.

    THE LIMIT TRAVELS WITH IT. A flare returning to the same pixel night
    after night at low power is an inference from REPETITION, not a
    measurement of what is there, and fire got the mirror of this wrong on
    Serbia this week. Said once under the headline, not on every row.
    """
    ps = e.get("persistence") or {}
    v = ps.get("verdict")
    if not v:
        return ""
    if v == "fire_like":
        return ('<span class="rowlu">behaves like fire: %.1f%% of detections '
                'recur in the same cell</span>' % ps.get("recur_pct", 0))
    return ('<span class="rowlu rowlu-na">behaves like a fixed source: '
            '%.1f%% recur in the same cell</span>' % ps.get("recur_pct", 0))


def _row(e):
    """One country row. Context is not an anomaly and must not look like
    one, and a thin multiple must not look sturdy."""
    href = e["href"]
    if href.startswith("fires/"):
        href = href[len("fires/"):]
    ctx = e.get("volume_context") and not e.get("anomalous")
    # A qualifier on its own line rather than run on to the claim. Taken
    # from the interim fix on main, whose reasoning is right and worth
    # keeping: "this is normal" is a result, not a caveat, so it is set
    # plain and never in a warning colour.
    note = ""
    if ctx:
        note = ('<span class="rowqual">within its historical range; '
                'shown for scale</span>')
    elif not e.get("anomalous") and e.get("pinned"):
        # "not unusual today" USED TO BE APPENDED HERE AND CONTRADICTED THE
        # ROW IT SAT ON. Spain, France and the UK all carry a title reading
        # "Second-heaviest fire week since 2012" or similar, and the note
        # denied it on the same line. Spain was the clearest: rank 2 of 14
        # with z=1.92, which is not "not unusual" by any reading we take.
        #
        # The mistake was treating "cleared no gate" as "nothing to see".
        # They are different claims and only the first is ours to make from
        # this payload. A country can miss every threshold and still be
        # having its second-heaviest week on record, which is exactly what
        # these rows are. So the note now says only why the row is present,
        # and the title is left to make the claim.
        note = ('<span class="rowqual">shown every week so this country '
                'can be checked, whatever it is doing</span>')
    elif e.get("multiple_unstable"):
        note = ('<span class="rowqual">small baseline; rank is the '
                'sturdier reading</span>')
    return f"""
      <a class="row{' ctx' if ctx else ''}" href="{href}">
        <span class="stat">{e['stat']}</span>
        <span class="rowmain">
          <span class="region">{e['region']}</span>
          <span class="claim">{e['title']}</span>{note}{_lu_row(e)}{_persist_row(e)}
        </span>
        {_tag(e)}
      </a>"""


# The prose above the weak list describes fire's gate in words, and words
# are as capable of drifting out of date as a comparison is. The headings
# name no number for that reason, but one sentence still commits: "whether
# it is setting a record" is only a fair description of the record signal
# while it means rank 1.
#
# So the description is pinned to the constants it paraphrases and the
# build fails if they move. This is the cheap half of the lesson the
# verdict field taught: a threshold copied into a second place needs
# something that notices when the copies disagree, and a guard cannot be
# forgotten where a ticket can.
_PROSE_ASSUMES = {"RECORD_RANK": 1}


def _check_prose_assumptions():
    from fires import build_events as _be
    for name, expected in _PROSE_ASSUMES.items():
        actual = getattr(_be, name)
        if actual != expected:
            raise SystemExit(
                f"fires/build_page.py: {name} is now {actual}, and the "
                f"prose under the weak-signal list was written for "
                f"{expected}. It tells the reader the second reading is "
                f"'whether it is setting a record', which stops being true "
                f"once more than the top week qualifies. Reword the note, "
                f"then update _PROSE_ASSUMES.")


def build(events_doc, font_prefix="../fonts/", baseline=None):
    ev = events_doc["events"]
    window = ev[0]["source"] if ev else ""
    # The headline counted every country on the page and asserted all of
    # them were burning well above normal. Four are not: they are large,
    # above normal and explicitly NOT anomalous, and DR Congo sits at
    # exactly 1.0x. The live page said "15 countries are burning well
    # above their own seasonal normal" while its own data denied four of
    # them, which is a wrong claim rather than a loose one. It counts the
    # anomaly flag now, and the context countries are listed under their
    # own heading rather than folded into the number.
    # THE EU SEASON BLOCK, or nothing at all. An absent or unreadable
    # payload renders no section rather than an empty one: this figure is
    # on a different evidence basis from everything else on the page, so a
    # placeholder for it would be worse than its absence.
    eu_block, eu_css = EU_AREA.block(EU_AREA.load(REPO))

    anom = [e for e in ev if e.get("anomalous")]
    ctx = [e for e in ev if e.get("volume_context") and not e.get("anomalous")]
    rest = [e for e in ev if e not in anom and e not in ctx]

    # THE MULTIPLE-ALONE SPLIT. Fire emits `strength.verdict` for this and
    # the branch is on the VERDICT, never on `qualifies_on`. Their reason,
    # and it is right: comparing the signal list against ["multiple"] would
    # put fire's gate rule inside design's code, where it agrees today and
    # drifts silently the first time the gate moves, because the comparison
    # keeps evaluating and keeps returning something.
    #
    # What it fixes, on this week's data: Botswana at 2.5x sorted above the
    # United States at 2.3x and India at 2.2x, so a reader scanning down
    # read Botswana as the fourth most extreme fire situation on earth.
    # Botswana is 3rd in its own 14-year record with z=1.79, inside its
    # ordinary variation. The other two are having their heaviest weeks on
    # record. Sorting by multiple put the least corroborated country above
    # two of the best corroborated ones.
    weak = [e for e in anom
            if (e.get("strength") or {}).get("verdict") == "multiple_only"]
    strong = [e for e in anom if e not in weak]
    rows = [_row(e) for e in strong]
    weak_rows = [_row(e) for e in weak]
    ctx_rows = [_row(e) for e in ctx]
    rest_rows = [_row(e) for e in rest]

    # THE COUNT IS NOT A FINDING, SO IT IS NOT THE HEADLINE.
    #
    # This said "N countries are burning well above their own seasonal
    # normal". Tested against an empirical null on 2026-08-04, at
    # product's request and after crops reached the same conclusion
    # independently: running this gate on every historical year of the
    # same window, leave-one-out, an ORDINARY week produces 7.6
    # qualifiers, median 8, range 3 to 10. The ten we published ties the
    # historical maximum rather than exceeding it, and sits at the 85th
    # percentile. One year in six.
    #
    # Worse, the gate manufactures much of its own count. RECORD_RANK is
    # satisfied by each country exactly once across the record BY
    # CONSTRUCTION, so 94 countries over 13 years yields about seven
    # qualifiers every year whatever happens; it contributed 5 to 8 in
    # every year including the quiet one. A count with a floor under it
    # cannot be evidence of anything.
    #
    # The individual extremes are the finding and survive any null:
    # Greece at 11.5x is 4.5x its own previous record week. So the
    # headline leads with the largest anomaly and states the count
    # nowhere. The gate keeps RECORD_RANK for SELECTION, which is sound;
    # what it stops doing is generating a number we present as a claim.
    # Editor's approved sentence, shared with the front page so the two
    # surfaces cannot drift. This headline was changed to the leading
    # extreme before product's ruling arrived, which was right, but it
    # led with the AVERAGE multiple. Beating a record is a stronger kind
    # of claim than exceeding an average, and the average multiple is
    # closer in shape to the count we just removed. Editor's argument.
    # Leads on the best-corroborated extreme rather than the largest
    # multiple. Identical output this week, since Greece is both, and it
    # stops the headline being handed to a multiple-only country on a week
    # where one happens to top the sort. That follows editor's own argument
    # for the current sentence: a record is a stronger kind of claim than a
    # multiple over an average.
    lead = (strong or anom or ev or [None])[0]
    if lead:
        headline = lead_sentence(lead).rstrip(".") or (
            f"{lead['region']} is burning at {lead['stat']} its "
            f"average for this week of the year")
    else:
        headline = "No country is burning unusually this week"
    # The house masthead, shared with every other page rather than
    # reinvented here. Without it this page had no link home, no nav and
    # no About, so anyone landing on it first was stuck.
    # Listed, not counted. These are large and above their own normal
    # and did not clear the anomaly gate, so they belong on a world fire
    # map and are not news. The section says so in words rather than
    # relying on a reader noticing a lighter number.
    # The wording names NO THRESHOLD, deliberately. Saying "none is more
    # than two standard deviations above its own average" would encode
    # fire's gate in design's prose, which is the same drift the verdict
    # field exists to prevent, just moved from a comparison into a sentence.
    #
    # Nor does it say these countries are not unusual. Portugal, Syria and
    # Indonesia are each having their second-heaviest week since 2012 and
    # the row titles say so. The claim here is narrower and is the one the
    # payload supports: one reading is carrying this on its own.
    _check_prose_assumptions()
    weak_block = ("" if not weak_rows else
                  '<p class="sectionlabel">High against their own average, '
                  'and nothing else agrees</p>' +
                  "".join(weak_rows) +
                  '<p class="note">We take three readings of each country: '
                  'how it compares with its own average for this week of '
                  'the year, whether it is setting a record, and how far it '
                  'stands out from its own year-to-year spread. For the '
                  'countries above, at least two agree. For these, only the '
                  'first does. That does not make them quiet, and several '
                  'are having one of their heaviest weeks on this record; it '
                  'means the evidence is thinner, so they are listed apart '
                  'rather than ranked among the others.</p>')
    # Pinned countries, previously rendered in the same list as the
    # anomalies with nothing but a row note to separate them. Given their
    # own heading now: Spain and France sit at second-heaviest since 2012
    # and appearing directly under the anomaly list read as a claim we had
    # not made.
    rest_block = ("" if not rest_rows else
                  '<p class="sectionlabel">Shown every week, whatever they '
                  'are doing</p>' + "".join(rest_rows) +
                  '<p class="note">These countries are on the page every '
                  'week so that a reader can check them rather than take '
                  'our word for which places matter. Their presence here is '
                  'not a signal in either direction; read the week each one '
                  'is having off its own row.</p>')
    ctx_block = ("" if not ctx_rows else
                 '<p class="sectionlabel">Large, and within their own '
                 'normal range</p>' + "".join(ctx_rows) +
                 '<p class="note">These countries are burning at or above '
                 'their own average for this week and did not clear the '
                 'anomaly gate. They are here because a fire map that '
                 'omitted them would misrepresent where the world is '
                 'burning, and they are listed separately because '
                 'presenting them as anomalies would misrepresent '
                 'whether it is unusual.</p>')
    # THE ARCHIVE, LINKED FROM THE ONE PAGE THAT IMPLIES IT EXISTS. 31 of
    # 49 country pages were reachable only by knowing the URL, four of them
    # stories we published. This index shows the week's finding and would
